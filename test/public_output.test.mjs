import { test } from "node:test";
import assert from "node:assert/strict";
import { assertPublicText, publicPrViolations, publicCommentViolations, publicReviewHash } from "../lib/public_output.mjs";

test("public text rejects NUL bytes without exposing or rewriting metadata", () => {
  for (const text of ["\0private", "public\0private", "private\0"]) {
    assert.throws(() => assertPublicText(text, "PR title"), error => {
      assert.match(error.message, /PR title contains NUL bytes/); assert.doesNotMatch(error.message, /private/); return true;
    });
    assert.deepEqual(publicPrViolations({ title: text, body: "Valid body" }), ["PR title contains NUL bytes"]);
    assert.deepEqual(publicPrViolations({ title: "Valid title", body: text }), ["PR body contains NUL bytes"]);
    assert.deepEqual(publicCommentViolations([{ id: 1, body: text }]), ["PR comment 1 contains NUL bytes"]);
  }
  const valid = "Quotes: '\"; literal \\0; café 🔑\r\nsecond line.";
  assert.equal(assertPublicText(valid), valid);
});

test("public text rejects mixed case runner branding without silently rewriting evidence", () => {
  for (const text of ["Gallivant completed this", "generated by GALLIVANT", "proof: docs/gallivant-test.md", "<!-- gallivant -->"]) {
    assert.throws(() => assertPublicText(text), /Public text rejected/);
  }
  const body = "Checked test/export.test.mjs and CI run 142.";
  assert.equal(assertPublicText(body), body);
  assert.deepEqual(publicPrViolations({ title: "GALLIVANT fix", body }), ["PR title mentions the runner name"]);
});

test("public text progress fingerprints ignore API ordering but detect title and comment corrections", () => {
  const pr = { title: "Export CSV", body: "Verified exports." };
  const comments = [{ id: 1, body: "Fixed.", created_at: "a" }, { id: 2, body: "Verified." }];
  assert.equal(publicReviewHash(pr, comments), publicReviewHash(pr, [...comments].reverse()));
  assert.notEqual(publicReviewHash(pr, comments), publicReviewHash({ ...pr, title: "Export JSON" }, comments));
  assert.notEqual(publicReviewHash(pr, comments), publicReviewHash(pr, [{ id: 1, body: "Fixed and tested." }, comments[1]]));
});
